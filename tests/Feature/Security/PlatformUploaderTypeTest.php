    // ---------------------------------------------------------------------------------------------------------------------------
    // a write that failed is a failure
    // ---------------------------------------------------------------------------------------------------------------------------

    /**
     * The `theme` disk is configured `throw => false`, so a failed write is a `false` return that used to be reported as success --
     * by every one of the writers, each of which has its own check. `multi_upload_file` writes to the disk NAMED by the storage setting.
     */
    /** A disk whose every write returns `false` (the `theme` disk is configured `throw => false`, which is how a failed write looks). */
    private function failingDisk(): object
    {
        // a directory of its own: createAndSetPermissionsRecursively() chmods whatever path() answers to 0777, and the system's temp
        // directory is not ours to chmod (it drops the sticky bit)
        $root = sys_get_temp_dir() . '/ssup-failing-' . bin2hex(random_bytes(4));
        mkdir($root, 0755, true);
        $this->temporary[] = $root;

        return new class($root) {
            public function __construct(public string $root)
            {
            }

            public function exists(...$arguments)
            {
                return true;
            }

            public function path(...$arguments)
            {
                return $this->root;
            }

            public function makeDirectory(...$arguments)
            {
                return true;
            }

            public function putFileAs(...$arguments)
            {
                return false;
            }

            // what a remote disk answers for a path it never wrote; the code under test reaches it when it does not check the write
            public function url(...$arguments)
            {
                return 'https://example.test/never-written';
            }
        };
    }

    #[DataProvider('theForms')]
    public function test_a_write_that_failed_is_reported_as_a_failure_by_every_form(string $form): void
    {
        Storage::set($form === 'multi_upload_file' ? 'local' : 'theme', $this->failingDisk());

        $result = $this->through($form, $this->upload('logo.png', $this->png()), '41_1795000000_logo.png');

        $this->assertSame(0, (int) ($result['flag'] ?? -1), "{$form} reported a write that failed as a stored file: " . json_encode($result));
    }

    /** @return array<string, array{0: string, 1: string}> the three functions that have a branch of their own for each remote disk */
    public static function theRemoteForms(): array
    {
        $cases = [];

        foreach (['upload_file', 'keyWiseUpload_file', 'jsonUpload_file'] as $form) {
            foreach (['s3', 'wasabi'] as $backend) {
                $cases["{$form} on {$backend}"] = [$form, $backend];
            }
        }

        return $cases;
    }

    /**
     * THE LOCAL BRANCH CHECKED THE WRITE AND THE TWO REMOTE ONES DID NOT: `putFileAs()` returns `false` on a failure, and the s3 and wasabi
     * branches went on to build a URL from it and answered success. The control is the same configuration with a disk that writes.
     */
    #[DataProvider('theRemoteForms')]
    public function test_a_write_that_failed_on_a_remote_disk_is_reported_as_a_failure(string $form, string $backend): void
    {
        $this->platformStorage(backend: $backend);

        Storage::fake($backend);
        $working = $this->through($form, $this->upload('logo.png', $this->png()), '41_1795000000_logo.png');
        $this->assertSame(1, (int) ($working['flag'] ?? -1), "Premise: {$form} stores through a working {$backend} disk. Answer: " . json_encode($working));

        Storage::set($backend, $this->failingDisk());
        $failed = $this->through($form, $this->upload('logo.png', $this->png()), '41_1795000000_logo.png');

        $this->assertSame(0, (int) ($failed['flag'] ?? -1), "{$form} reported a write that failed on {$backend} as a stored file: " . json_encode($failed));
    }
