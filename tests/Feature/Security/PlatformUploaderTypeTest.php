    /**
     * `'mimes:'` with an empty list parses to `[null]`, which the rule compares loosely: PHP source was stored as `.png`. Four of the five
     * forms refuse everything under an empty list; `multi_upload_file` has a default list of its own for an empty setting
     * (`jpeg,jpg,png,svg,zip,txt,gif,docx`) -- a legacy behaviour, pinned here as what it is, so nobody reads the name of this test as a
     * claim about it. (The review of the first form measured it.)
     */
    public function test_an_empty_list_refuses_everything_and_does_not_pass_everything(): void
    {
        $this->platformStorage(validation: '');      // an EMPTY value: `!empty()` is false, so the code's own fallback is `''`

        foreach (self::theForms() as $label => [$form]) {
            $this->emptyTheDisks();
            $png = $this->through($form, $this->upload('logo.png', $this->png()), '41_1795000000_logo.png');
            $this->emptyTheDisks();
            $php = $this->through($form, $this->upload('x.png', self::PHP), '41_1795000000_x.png');

            $this->assertSame(0, (int) ($php['flag'] ?? -1), "{$label}: PHP source was stored under an image name because the configured list was empty: " . json_encode($php));

            if ($form === 'multi_upload_file') {
                $this->assertSame(1, (int) $png['flag'], 'multi_upload_file lost the default list it has for an empty setting: ' . json_encode($png));

                continue;
            }

            $this->assertSame(0, (int) $png['flag'], "{$label} stored a PNG under an empty list: " . json_encode($png));
            $this->assertSame('No file type is enabled for uploads.', $png['msg'], 'An empty list is refused as one, not by whichever rule happens to fail first.');
            $this->assertSame([], $this->stored());
        }
    }

    /** The configured size ceiling still applies on every form, the sixth-argument one included. */
    public function test_the_configured_size_ceiling_applies_to_every_form(): void
    {
        $this->platformStorage(maxKb: '1');
        $big = $this->png() . str_repeat("\0", 3 * 1024);

        foreach (self::theForms() as $form => [$name]) {
            Storage::fake('theme');
            Storage::fake('local');

            $over = $this->through($name, $this->upload('big.png', $big), '41_1795000000_big.png');
