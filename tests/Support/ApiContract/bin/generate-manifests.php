#!/usr/bin/env php
<?php

/**
 * Regenerates the committed API contract manifests.
 *
 * Run this whenever StoreSyria_app98/lib/utils/base_api.dart changes. The manifests are
 * committed so that check-contract.php can run in a server-only CI job that has no
 * checkout of the Flutter repo.
 *
 * USAGE
 *   php tests/Support/ApiContract/bin/generate-manifests.php --app-repo=/path/to/StoreSyria_app98
 *
 * Runs with nothing but `php` -- no vendor/, no database, no network.
 */

declare(strict_types=1);

require __DIR__ . '/../FlutterEndpointExtractor.php';
require __DIR__ . '/../RouteFileParser.php';

use Tests\Support\ApiContract\FlutterEndpointExtractor;
use Tests\Support\ApiContract\RouteFileParser;

$root    = dirname(__DIR__, 4);
$options = getopt('', ['app-repo:']) ?: [];
$appRepo = $options['app-repo'] ?? null;

if (!is_string($appRepo) || $appRepo === '') {
    fwrite(STDERR, "--app-repo=/path/to/StoreSyria_app98 is required.\n");
    exit(2);
}

$dartPath = rtrim($appRepo, '/') . '/lib/utils/base_api.dart';

if (!is_readable($dartPath)) {
    fwrite(STDERR, "Not readable: {$dartPath}\n");
    exit(2);
}

$extracted = FlutterEndpointExtractor::extract((string) file_get_contents($dartPath));

// The base URL names a production host. Only its PATH is recorded; the host is
// deliberately dropped so the manifest carries no environment detail.
$endpointManifest = [
    '_comment'   => 'GENERATED by tests/Support/ApiContract/bin/generate-manifests.php. '
        . 'The endpoint surface of the shipped Flutter admin app, extracted from '
        . 'lib/utils/base_api.dart. Do not hand-edit; regenerate.',
    '_source'    => 'StoreSyria_app98/lib/utils/base_api.dart',
    'base_path'  => $extracted['base_path'],
    'endpoints'  => $extracted['endpoints'],
    'fragments'  => $extracted['fragments'],
];

$outDir = __DIR__ . '/../manifests';

if (!is_dir($outDir) && !mkdir($outDir, 0o755, true) && !is_dir($outDir)) {
    fwrite(STDERR, "Could not create {$outDir}\n");
    exit(2);
}

$flutterOut = $outDir . '/flutter-endpoints.json';
file_put_contents(
    $flutterOut,
    json_encode($endpointManifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n"
);

// A snapshot of the server side too, so a reviewer can diff the contract over time
// without needing either a database or a Flutter toolchain.
$parsed     = RouteFileParser::parse((string) file_get_contents($root . '/routes/api.php'));
$serverUris = array_values(array_unique(array_map(
    static fn (array $r): string => $r['uri'],
    $parsed['routes']
)));
sort($serverUris);

$routesOut = $outDir . '/server-api-routes.json';
file_put_contents($routesOut, json_encode([
    '_comment'    => 'GENERATED. API route paths parsed from routes/api.php. Module route '
        . 'files are resolved at check time, not snapshotted here.',
    '_source'     => 'routes/api.php',
    'count'       => count($serverUris),
    'unsupported' => $parsed['unsupported'],
    'routes'      => $serverUris,
], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");

fwrite(STDOUT, sprintf(
    "Wrote %d app endpoints to %s\nWrote %d server routes to %s\n",
    count($extracted['endpoints']),
    $flutterOut,
    count($serverUris),
    $routesOut
));
