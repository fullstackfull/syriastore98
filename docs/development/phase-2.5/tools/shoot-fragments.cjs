/**
 * `{orderEnc}` IN A ROUTE, because three of these surfaces live behind an ENCRYPTED id.
 *
 * `order-view/{id}` and `order-receipt/{id}` both open `Crypt::decrypt($id)`
 * (OrderController.php:819 and :1258), and the list screens link them with
 * `Crypt::encrypt($order->id)` (order/action.blade.php:78, order/view.blade.php:31). A plain
 * integer is NOT a shorter spelling of the same thing: probe-package-c-reachability.cjs measured
 * three such routes answering 200 back on /dashboard from a caught DecryptException and two
 * answering an uncaught 500. Two of the three were surfaces the matrix already records as
 * verified, so the obvious reading was that something had broken. Nothing had -- the probe was
 * asking with a token the application cannot decrypt.
 *
 * The token is generated by booting the real application so the real APP_KEY is used; a
 * hand-built one would not decrypt. CLAUDE.md records that APP_KEY is in git history and
 * unrotated, so this is an ENCODING and not a control -- a recorded security finding, and not
 * this harness's business. What matters here is only that it is the URL FORMAT the screens need.
 */
function encryptOrderId(plainId) {
  const php = `
    require '${REPO}/vendor/autoload.php';
    $app = require_once '${REPO}/bootstrap/app.php';
    $app->make(Illuminate\\Contracts\\Console\\Kernel::class)->bootstrap();
    echo Illuminate\\Support\\Facades\\Crypt::encrypt(${JSON.stringify(String(plainId))});
  `;
  return execFileSync('php', ['-r', php], {
    encoding: 'utf8',
    env: Object.assign({}, process.env, {
      DB_CONNECTION: 'sqlite',
      DB_DATABASE: path.join(REPO, 'database/p2dev.sqlite'),
      CACHE_STORE: 'file',
      SESSION_DRIVER: 'file',
    }),
  }).trim();
}

/** The lowest order id in the fixture store -- the one the notes above were seeded onto. */
function fixtureOrderId() {
  const php = `
    $pdo = new PDO('sqlite:' . ${JSON.stringify(REPO + '/database/p2dev.sqlite')});
    echo (int) $pdo->query('SELECT MIN(id) FROM orders WHERE store_id = ' . (int) ${JSON.stringify(STORE)})->fetchColumn();
  `;
  return execFileSync('php', ['-r', php], { encoding: 'utf8' }).trim();
}

